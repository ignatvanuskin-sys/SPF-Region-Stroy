export function faqById(id: string): FaqItem | undefined {
  return FAQ.find((f) => f.id === id);
}

export function faqByIds(ids: string[]): FaqItem[] {
  return ids.map(faqById).filter((f): f is FaqItem => Boolean(f));
}

